/** 14 对 PM 矛盾映射（素材 §三）。 */
export interface TrizPmContradictionPair {
  /** 稳定标识 PM-01…PM-14，与素材「矛盾对 N」一一对应 */
  id: string
  /** 矛盾对标题（素材原文） */
  title: string
  /** 场景描述 */
  scenario: string
  /** 改善参数编号集合（素材以 #N 标注，通常单值） */
  improvingParameterNumbers: readonly number[]
  /** 改善参数原文标注（含素材给出的软件语义箭头） */
  improvingParameterNote: string
  /** 恶化参数编号集合 */
  worseningParameterNumbers: readonly number[]
  /** 恶化参数原文标注 */
  worseningParameterNote: string
  /** 推荐原则编号集合，按素材给出的顺序 */
  principleNumbers: readonly number[]
  /** 场景解法要点（按素材分号切分，顺序保持） */
  solutions: readonly string[]
  /** 来源章节标注 */
  source: string
}

