// 自检：模块加载不做校验（零副作用），测试/启动时显式调用 validate()。

export default class DatabaseIsolationCatalog {
  private static readonly declarations = new Map<string, DatabaseTableDeclaration>(
    DATABASE_TABLE_DECLARATIONS.map((d) => [d.tableName, d]),
  )

  static validate(): void {
    for (const decl of DATABASE_TABLE_DECLARATIONS) {
      const errors = validateDatabaseTableDeclaration(decl)
      if (errors.length > 0) {
        throw new Error(
          `DatabaseIsolationCatalog: 声明非法 tableName=${decl.tableName}: ${errors.join('; ')}`,
        )
      }
    }
    const integrity = validateCatalogIntegrity(DATABASE_TABLE_DECLARATIONS)
    const tables = Object.keys(integrity)
    if (tables.length > 0) {
      throw new Error(
        `DatabaseIsolationCatalog: 目录完整性失败: ${tables.map((t) => `${t}->${integrity[t].join('; ')}`).join(' | ')}`,
      )
    }
  }

  static get(tableName: string): DatabaseTableDeclaration {
    const decl = this.declarations.get(tableName)
    if (!decl) {
      throw new Error(`DatabaseIsolationCatalog: 未登记表 ${tableName}`)
    }
    return decl
  }

  static has(tableName: string): boolean {
    return this.declarations.has(tableName)
  }

  static all(): readonly DatabaseTableDeclaration[] {
    return DATABASE_TABLE_DECLARATIONS
  }

  static classificationOf(tableName: string): DatabaseIsolationClassification {
    return this.get(tableName).classification
  }

  static organizationColumnOf(tableName: string): string | null {
    return this.get(tableName).organizationColumn ?? null
  }

  static parentResolversOf(tableName: string): readonly DatabaseParentResolver[] {
    return this.get(tableName).parentResolvers ?? []
  }

  static assertGlobalAllowed(tableName: string): void {
    const decl = this.get(tableName)
    if (!decl.globalException || !decl.globalException.allowed) {
      throw new PermissionDeniedException(
        `DatabaseIsolationCatalog: ${tableName} 全局访问未显式允许`,
      )
    }
  }
}
