export interface AuditEntry {
  event: AuditEventType
  severity?: 'info' | 'warning' | 'error' | 'critical'
  userId?: number | null
  organizationId?: number | null
  projectId?: number | null
  entityType?: string | null
  entityId?: number | null
  requestId?: string | null
  changes?: { before?: Record<string, unknown>; after?: Record<string, unknown> } | null
  metadata?: Record<string, unknown> | null
  /** 业务结构变更要求审计原子落库时传入同一事务。 */
  client?: TransactionClientContract
  /** 原子业务审计失败时向上抛出，使外层事务回滚。 */
  strict?: boolean
}

/**
 * 审计服务：把认证/权限事件写入既有 `audit_logs`（design D12）。
 *
 * 设计为**不阻塞主请求**：写入失败仅记日志、绝不向上抛错，避免审计故障影响业务。
 * 调用方可 `await` 以保证测试可断言，也可 `void` 触发即走。
 */
export default class AuditService {
  async log(entry: AuditEntry): Promise<void> {
    try {
      const created = await AuditLog.create(
        {
          action: EVENT_TO_ACTION[entry.event],
          severity: entry.severity ?? 'info',
          userId: entry.userId ?? null,
          organizationId: entry.organizationId ?? null,
          projectId: entry.projectId ?? null,
          entityType: entry.entityType ?? null,
          entityId: entry.entityId ?? null,
          requestId: entry.requestId ?? null,
          changes: entry.changes ? AuditService.sanitize(entry.changes) : null,
          metadata: AuditService.sanitize({ ...(entry.metadata ?? {}), event: entry.event }),
        },
        entry.client ? { client: entry.client } : undefined,
      )

      // Timeline 实时旁路：仅对映射表允许的事件发提示；失败绝不影响审计写入
      this.broadcastTimelineHint(entry, created.id)

      // 插件事件订阅旁路（v3-plugin-event-subscription-contract）：核心事务成功后投影最小 envelope；
      // fire-and-forget，失败绝不影响审计写入（与 timeline hint 同语义）。
      void this.tryProjectPluginEvents(entry, created.id)
    } catch (error) {
      logger.error({ err: error, event: entry.event }, 'audit log write failed')
      if (entry.strict) throw error
    }
  }

  /**
   * 插件事件订阅投影旁路（v3-plugin-event-subscription-contract，D2）。
   *
   * 旁路语义：fire-and-forget，失败绝不影响审计写入；动态 import 打破循环依赖。
   */
  private async tryProjectPluginEvents(entry: AuditEntry, auditLogId: number): Promise<void> {
    try {
      const { default: PluginEventProjectorService } =
        await import('#services/plugin_event_subscription/projector_service')
      const projector = new PluginEventProjectorService()
      await projector.projectFromAuditEntry(entry, auditLogId)
    } catch (error) {
      logger.warn(
        { event: entry.event, error: error instanceof Error ? error.message : 'unknown' },
        '插件事件投影旁路失败（不影响审计写入）',
      )
    }
  }

  /**
   * 向项目 room 推送 timeline:activity 失效提示。
   *
   * 旁路语义：fire-and-forget，失败绝不影响审计写入。
   * 用动态 import 打破 `audit_service` ⇄ `timeline_event_mapping` 的循环依赖
   *（后者需引用 `AuditEvent` 值构建 allowlist；静态互引会在模块初始化期触发 TDZ）。
   */
  private broadcastTimelineHint(entry: AuditEntry, auditLogId: number): void {
    void this.tryBroadcastTimelineHint(entry, auditLogId)
  }

  private async tryBroadcastTimelineHint(entry: AuditEntry, auditLogId: number): Promise<void> {
    const organizationId = entry.organizationId
    const projectId = entry.projectId
    if (typeof organizationId !== 'number' || typeof projectId !== 'number') return
    try {
      const { isTimelineCandidate } = await import('#services/timeline/timeline_event_mapping')
      if (!isTimelineCandidate(entry.event, entry.metadata ?? null)) return

      const broadcaster = new RealtimeBroadcaster()
      broadcaster.broadcastToProject(organizationId, projectId, {
        type: RealtimeEvents.TIMELINE_ACTIVITY,
        projectId,
        entityId: auditLogId,
        actorId: entry.userId ?? 0,
        occurredAt: new Date().toISOString(),
        metadata: { category: 'timeline' },
      })
    } catch (error) {
      logger.warn(
        {
          event: entry.event,
          error: error instanceof Error ? error.message : 'unknown',
        },
        'Timeline 实时旁路失败（不影响审计写入）',
      )
    }
  }

  /**
   * 敏感字段脱敏 + 超长截断（design D5）。
   */
  static sanitize<T>(value: T, _truncated?: { value: boolean }): T {
    const state = _truncated ?? { value: false }

    if (typeof value === 'string') {
      const text = value as string
      if (new TextEncoder().encode(text).length > 5120) {
        state.value = true
        return text.slice(0, 1024) as T
      }
      return value
    }

    if (Array.isArray(value)) {
      return value.map((item) => AuditService.sanitize(item, state)) as T
    }

    if (value !== null && typeof value === 'object') {
      const result: Record<string, unknown> = {}
      const sensitiveFields = new Set([
        'password',
        'passwordhash',
        'token',
        'refreshtoken',
        'accesstoken',
        'access_token',
        'apikey',
        'api_key',
        'secret',
        'client_secret',
        'authorization',
      ])

      for (const [key, val] of Object.entries(value as Record<string, unknown>)) {
        const lowerKey = key.toLowerCase()
        const isSensitive = [...sensitiveFields].some((field) => lowerKey.includes(field))
        if (isSensitive) {
          result[key] = '***'
        } else {
          result[key] = AuditService.sanitize(val, state)
        }
      }

      const serialized = JSON.stringify(result)
      if (new TextEncoder().encode(serialized).length > 5120) {
        state.value = true
      }

      if (state.value) {
        result.truncated = true
      }

      return result as T
    }

    return value
  }
}
