/**
 * v3-service-architecture-expansion — markdown inventory section generator.
 *
 * Regenerates a markdown summary of the service architecture catalog for
 * observation-and-inventory.md without touching runtime data.
 * Task 3.6 (P1): optional script/test helper.
 */
import { type ServiceCatalogEntry, type ServiceArchitectureFinding } from '@aiproj/types'
import { SERVICE_ARCHITECTURE_CATALOG } from './catalog.js'
import { summarizeInventoryFindings } from './inventory_checker.js'

/**
 * Generate a markdown table of catalog entries.
 */
export function generateCatalogMarkdown(
  entries: readonly ServiceCatalogEntry[] = SERVICE_ARCHITECTURE_CATALOG,
): string {
  const header =
    '| Module Key | Role | Owner | Tenant Mode | Side-Effect | External Action | Audit/Ledger | Evidence |\n' +
    '|------------|------|-------|--------------|-------------|-----------------|--------------|----------|\n'
  const rows = entries
    .map(
      (e) =>
        '| ' +
        e.moduleKey +
        ' | ' +
        e.role +
        ' | ' +
        e.ownerDomain +
        ' | ' +
        e.tenantMode +
        ' | ' +
        e.sideEffectClass +
        ' | ' +
        e.externalActionClass +
        ' | ' +
        e.auditLedgerExpectation +
        ' | ' +
        e.evidenceFreshness +
        ' |\n',
    )
    .join('')
  return header + rows
}

/**
 * Generate a markdown list of findings (low-sensitive).
 */
export function generateFindingsMarkdown(findings: ServiceArchitectureFinding[]): string {
  const summaries = summarizeInventoryFindings(findings)
  if (summaries.length === 0) {
    return '_No architecture findings._\n'
  }
  const header =
    '| Module | Category | Reason Code | Severity | Message | Evidence |\n' +
    '|--------|----------|-------------|----------|---------|----------|\n'
  const rows = summaries
    .map(
      (s) =>
        '| ' +
        s.moduleKey +
        ' | ' +
        s.category +
        ' | ' +
        s.reasonCode +
        ' | ' +
        s.severity +
        ' | ' +
        s.message +
        ' | ' +
        s.evidenceFreshness +
        ' |\n',
    )
    .join('')
  return header + rows
}

/**
 * Generate the full inventory markdown section.
 */
export function generateInventorySection(
  findings: ServiceArchitectureFinding[] = [],
  entries: readonly ServiceCatalogEntry[] = SERVICE_ARCHITECTURE_CATALOG,
): string {
  const registered = entries.filter((e) => e.role !== 'legacy-service')
  const legacy = entries.filter((e) => e.role === 'legacy-service')
  const lines: string[] = []
  lines.push('## Service Architecture Catalog (Generated)')
  lines.push('')
  lines.push('> Auto-generated by `generateInventorySection()`. Do not edit manually.')
  lines.push('')
  lines.push('### Registered Entries (' + registered.length + ')')
  lines.push('')
  lines.push(generateCatalogMarkdown(registered))
  lines.push('### Legacy / Deferred Entries (' + legacy.length + ')')
  lines.push('')
  lines.push(generateCatalogMarkdown(legacy))
  lines.push('### Architecture Findings')
  lines.push('')
  lines.push(generateFindingsMarkdown(findings))
  return lines.join('\n')
}

export { SERVICE_ARCHITECTURE_CATALOG }
